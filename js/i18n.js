let lang = 'ja';

export function resolveLang(setting, navLang = globalThis.navigator?.language || 'ja') {
  if (setting === 'ja' || setting === 'en') return setting;
  return String(navLang).toLowerCase().startsWith('ja') ? 'ja' : 'en';
}

export function setLang(l) {
  lang = l;
  document.documentElement.lang = l;
}

export const getLang = () => lang;

export function t(key, params = {}) {
  const s = dict[lang][key] ?? dict.ja[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '');
}

// 日付（YYYY-MM-DD）を言語に合わせて書く。ja: 2026/11/11（水） en: Wed, Nov 11, 2026
export function formatDate(ymd, l = lang) {
  const [y, m, d] = ymd.split('-').map(Number);
  const date = new Date(y, m - 1, d);
  if (l === 'ja') {
    const w = '日月火水木金土'[date.getDay()];
    return `${y}/${String(m).padStart(2, '0')}/${String(d).padStart(2, '0')}（${w}）`;
  }
  return date.toLocaleDateString('en-US', { weekday: 'short', month: 'short', day: 'numeric', year: 'numeric' });
}
